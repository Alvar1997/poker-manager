export type AuditAction = (typeof AUDIT_ACTIONS)[keyof typeof AUDIT_ACTIONS]

export type AuditResultValue = "SUCCESS" | "FAILURE" | "DENIED"

export type AuditEntry = {
  action: AuditAction
  entityType: string
  entityId?: string | null
  actorUserId?: string | null
  result?: AuditResultValue
  requestId?: string | null
  metadata?: Record<string, unknown>
  // Módulo 15: columnas explícitas (si no se dan, se derivan de metadata).
  actorRole?: "SUPERADMIN" | "PARTNER" | "CASHIER" | null
  sessionId?: string | null
  playerId?: string | null
  tableCycleId?: string | null
  idempotencyKey?: string | null
  reason?: string | null
  relatedEventId?: string | null
  amount?: string | null
  evidenceRef?: string | null
}

export type DbClient = Prisma.TransactionClient | typeof prisma

const FORBIDDEN_KEY = /pass(word)?|hash|token|secret|cookie|authorization/i

/** Elimina recursivamente claves que puedan contener secretos. */
export function sanitizeMetadata(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sanitizeMetadata)
  if (value instanceof Date) return value.toISOString()
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>)
        .filter(([key]) => !FORBIDDEN_KEY.test(key))
        .map(([key, v]) => [key, maskValue(key, sanitizeMetadata(v))])
    )
  }
  return value
}

/**
 * Cambios campo a campo `{ campo: { from, to } }` entre el estado previo y
 * lo que se envió (ignora campos no enviados o sin cambio). null si nada
 * cambió — en ese caso no se audita una "edición" vacía.
 */
export function diffChanges(
  before: Record<string, unknown>,
  input: Record<string, unknown>
): Record<string, { from: unknown; to: unknown }> | null {
  const changes: Record<string, { from: unknown; to: unknown }> = {}
  for (const [key, to] of Object.entries(input)) {
    if (to !== undefined && before[key] !== to) {
      changes[key] = { from: before[key], to }
    }
  }
  return Object.keys(changes).length > 0 ? changes : null
}

/**
 * Inserta un evento de auditoría (solo inserción: trigger en BD). Se llama
 * DENTRO de la transacción de la operación (`db` = tx) para que operación
 * y evento sean atómicos (Módulo 15 §6). El rol del actor se fija al
 * momento del evento y las columnas transversales se derivan de los
 * metadatos (sesión, jugador, ciclo, importe…), sin inventar datos.
 */
export async function recordAudit(
  entry: AuditEntry,
  db: DbClient = prisma
): Promise<{ id: string }> {
  const derived = deriveAuditColumns(entry.action, entry.metadata)
  let actorRole = entry.actorRole ?? null
  if (!actorRole && entry.actorUserId) {
    const actor = await db.user.findUnique({
      where: { id: entry.actorUserId },
      select: { role: true },
    })
    actorRole = actor?.role ?? null
  }
  return db.auditLog.create({
    data: {
      action: entry.action,
      entityType: entry.entityType,
      entityId: entry.entityId ?? null,
      actorUserId: entry.actorUserId ?? null,
      result: entry.result ?? "SUCCESS",
      requestId: entry.requestId ?? null,
      metadata: entry.metadata
        ? (sanitizeMetadata(entry.metadata) as Prisma.InputJsonValue)
        : undefined,
      actorRole,
      module: derived.module,
      sessionId: entry.sessionId ?? derived.sessionId,
      playerId: entry.playerId ?? derived.playerId,
      tableCycleId: entry.tableCycleId ?? derived.tableCycleId,
      idempotencyKey: entry.idempotencyKey ?? derived.idempotencyKey,
      reason: entry.reason ?? derived.reason,
      relatedEventId: entry.relatedEventId ?? null,
      amount: entry.amount ?? derived.amount,
      evidenceRef: entry.evidenceRef ?? derived.evidenceRef,
    },
    select: { id: true },
  })
}

/**
 * Variante que nunca lanza: para eventos que no deben bloquear la
 * respuesta (accesos denegados, logins fallidos, logout). Si falla, queda
 * en el log del servidor.
 */
export async function recordAuditSafe(entry: AuditEntry): Promise<void> {
  try {
    await recordAudit(entry)
  } catch (error) {
    logger.error({
      event: "audit_write_failed",
      action: entry.action,
      requestId: entry.requestId,
      err: error,
    })
  }
}
